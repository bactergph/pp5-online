export function readingRubricForIndicator(band: EducationBand, shortLabel: string): RubricLevels | null {
  for (const standard of READING_BAND_STANDARDS[band]) {
    const indicator = standard.indicators.find(item => item.shortLabel === shortLabel)
    if (indicator) return indicator.rubricLevels
  }
  return null
}
