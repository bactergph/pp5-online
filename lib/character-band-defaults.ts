export function educationBandFromClassroomLevel(level: string): EducationBand {
  const normalized = (level || '').replace(/\s+/g, '').toLowerCase()

  if (/^ป\.?[1-3]$/.test(normalized) || /ประถม.*([1-3]|ปี[1-3])/.test(normalized)) return '1'
  if (/^ป\.?[4-6]$/.test(normalized) || /ประถม.*([4-6]|ปี[4-6])/.test(normalized)) return '2'
  if (/^ม\.?[1-3]$/.test(normalized) || /มัธยม.*([1-3]|ปี[1-3])/.test(normalized)) return '3'
  if (/^ม\.?[4-6]$/.test(normalized) || /มัธยม.*([4-6]|ปี[4-6])/.test(normalized)) return '4'

  return '4'
}
