const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
const vm = require('node:vm')
const mod = {}
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/roles.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports: mod })
const director = mod.splitThaiStaffName('นายปราโมท คำเพชรดี')
assert.equal(director.prefix, 'นาย')
assert.equal(director.full_name, 'ปราโมท คำเพชรดี')
assert.equal(mod.splitThaiStaffName('นางสาว ศิวาพร ใจดี').prefix, 'นางสาว')
assert.equal(mod.splitThaiStaffName('นางสาว ศิวาพร ใจดี').full_name, 'ศิวาพร ใจดี')
assert.equal(mod.formatStaffName(director.prefix, director.full_name), 'นายปราโมท คำเพชรดี')
assert.equal(mod.splitThaiStaffName('  ').full_name, '')
console.log('PASS: typed leader names split into prefix and full name')
